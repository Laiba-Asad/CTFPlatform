/**
 * npm run flag:hash
 *
 * Combines seed/challenges.meta.json (editable, no secrets) with the plaintext
 * flags in challenge-services/.flags.env into seed/challenges.json, replacing
 * each flag with a salted HMAC using FLAG_PEPPER. Plaintext flags never touch
 * seed/challenges.json. Re-run this whenever FLAG_PEPPER or a flag changes.
 *
 * The flag values are read and hashed but never printed.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadConfig } from '../config';
import { API_ROOT } from '../db-url';
import { hashFlag } from '../services/flags';
import { runScript } from './cli';

const REPO = resolve(API_ROOT, '../..');
const META = resolve(REPO, 'seed/challenges.meta.json');
const OUT = resolve(REPO, 'seed/challenges.json');
const FLAGS_ENV = resolve(REPO, 'challenge-services/.flags.env');

function parseEnvFile(path: string): Record<string, string> {
  const env: Record<string, string> = {};
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq > 0) env[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim();
  }
  return env;
}

runScript(async () => {
  if (!existsSync(FLAGS_ENV)) {
    throw new Error(`Missing ${FLAGS_ENV}\nRun: python challenge-services/build_flags_env.py <path-to-old-app.py>`);
  }
  const config = loadConfig();
  if (config.usingDevSecrets) {
    console.warn('WARNING: hashing with the development FLAG_PEPPER. Set a real FLAG_PEPPER before the event and re-run.');
  }
  const flags = parseEnvFile(FLAGS_ENV);
  const meta = JSON.parse(readFileSync(META, 'utf8')) as { challenges: Array<Record<string, unknown>> };

  const out = meta.challenges.map((c) => {
    const id = c.id as string;
    const plain = flags[`FLAG_${id}`];
    if (!plain) throw new Error(`No FLAG_${id} in .flags.env`);
    const { salt, hash } = hashFlag(config.flagPepper, plain);
    const { ...rest } = c;
    return { ...rest, flagSalt: salt, flagHash: hash, released: false };
  });

  writeFileSync(
    OUT,
    JSON.stringify(
      { _comment: 'GENERATED by `npm run flag:hash` from challenges.meta.json + .flags.env. No plaintext flags. Hashes depend on FLAG_PEPPER; re-generate if it changes.', challenges: out },
      null,
      2,
    ) + '\n',
  );
  console.log(`Wrote ${OUT} with ${out.length} challenges (no plaintext flags).`);
});

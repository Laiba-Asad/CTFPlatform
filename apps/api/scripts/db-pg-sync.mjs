#!/usr/bin/env node
/**
 * Keep the PostgreSQL schema and migrations in step with prisma/schema.prisma.
 *
 *   npm run db:pg-sync -w @cydemic/api -- <migration_name>
 *
 * 1. Derives prisma/postgresql/schema.prisma (same models, postgresql provider).
 * 2. Diffs the previous PostgreSQL schema against the new one (offline, no
 *    database needed) and writes the SQL as a new migration.
 * Run it whenever you add a SQLite migration, and commit both.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const apiRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(apiRoot, 'prisma', 'schema.prisma');
const pgDir = join(apiRoot, 'prisma', 'postgresql');
const pgSchema = join(pgDir, 'schema.prisma');
const pgMigrations = join(pgDir, 'migrations');
const name = (process.argv[2] || 'sync').replace(/[^a-z0-9_]/gi, '_').toLowerCase();

const derived = readFileSync(source, 'utf8')
  .replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"')
  .replace('output       = "../src/generated/prisma"', 'output       = "../../src/generated/prisma"')
  .replace(/^\/\/ Cydemic CTF data model\./m, '// GENERATED by scripts/db-pg-sync.mjs from prisma/schema.prisma. Do not edit.\n// Cydemic CTF data model.');

if (!derived.includes('provider = "postgresql"') || !derived.includes('../../src/generated/prisma')) {
  console.error('Could not derive the PostgreSQL schema: datasource or generator block changed shape.');
  process.exit(1);
}

mkdirSync(pgMigrations, { recursive: true });
const next = join(pgDir, 'schema.next.prisma');
writeFileSync(next, derived);

const prisma = join(apiRoot, '..', '..', 'node_modules', 'prisma', 'build', 'index.js');
const from = existsSync(pgSchema) ? ['--from-schema', pgSchema] : ['--from-empty'];
let sql;
try {
  sql = execFileSync(process.execPath, [prisma, 'migrate', 'diff', ...from, '--to-schema', next, '--script'], {
    cwd: apiRoot,
    encoding: 'utf8',
    env: { ...process.env, DATABASE_URL: 'postgresql://offline:offline@localhost:5432/offline' },
  });
} catch (err) {
  rmSync(next);
  console.error(err.stdout || err.message);
  process.exit(1);
}

writeFileSync(pgSchema, derived);
rmSync(next);
writeFileSync(join(pgMigrations, 'migration_lock.toml'), '# Do not edit. Managed by Prisma.\nprovider = "postgresql"\n');

if (!/\b(CREATE|ALTER|DROP)\b/i.test(sql)) {
  console.log('PostgreSQL schema is up to date. No migration needed.');
  process.exit(0);
}

const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
const dir = join(pgMigrations, `${stamp}_${name}`);
mkdirSync(dir);
writeFileSync(join(dir, 'migration.sql'), sql);
console.log(`Wrote ${dir.replace(apiRoot, 'apps/api')}/migration.sql`);

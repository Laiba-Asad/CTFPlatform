#!/usr/bin/env node
/**
 * npm run prod:init
 *
 * One-time production setup on the VM. Creates .env with strong random secrets
 * and the detected LAN address, applies migrations, seeds the 15 challenges, and
 * rehashes every flag into the database with the new FLAG_PEPPER. Never
 * overwrites an existing .env without --force. Prints only counts, no secrets.
 *
 *   npm run prod:init                       # auto-detect IP, port 8080
 *   npm run prod:init -- --ip 192.168.1.50 --port 80 --admin-ip 192.168.1.20
 *   npm run prod:init -- --force            # overwrite an existing .env
 */
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { detectLanIp } from './lib/net.mjs';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const apiDir = join(repo, 'apps', 'api');
const isWin = process.platform === 'win32';
const envPath = join(repo, '.env');

const argv = process.argv.slice(2);
const flag = (name, def) => {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : def;
};
const has = (name) => argv.includes(`--${name}`);

async function confirm(question) {
  if (has('force')) return true;
  if (!process.stdin.isTTY) return false;
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  const a = await rl.question(question);
  rl.close();
  return a.trim().toLowerCase() === 'yes';
}

const run = (cmd, args, env = {}) =>
  execFileSync(isWin ? `${cmd}.cmd` : cmd, args, { cwd: repo, stdio: 'inherit', shell: isWin, env: { ...process.env, ...env } });

async function main() {
  const ip = flag('ip', detectLanIp());
  const port = flag('port', '8080');
  const adminIp = flag('admin-ip', '');
  const backupDir = flag('backup-dir', 'backups');
  const origin = `http://${ip}:${port}`;

  if (existsSync(envPath)) {
    console.log(`\n.env already exists at ${envPath}.`);
    if (!(await confirm('Overwrite it with a fresh production .env? Type "yes": '))) {
      console.log('Left the existing .env unchanged. (Use --force to overwrite.)');
      return;
    }
  }

  const secret = () => randomBytes(36).toString('base64url'); // ~48 chars
  const adminIps = ['127.0.0.1', '::1', ...(adminIp ? adminIp.split(',').map((s) => s.trim()).filter(Boolean) : [])];
  const lines = [
    '# Generated by npm run prod:init. Secret - never commit. Keep on the VM only.',
    'NODE_ENV=production',
    'HOST=0.0.0.0',
    `WEB_PORT=${port}`,
    'SERVE_WEB=true',
    `PUBLIC_URL=${origin}`,
    `ALLOWED_ORIGINS=${origin}`,
    'COOKIE_SECURE=false',
    'TRUST_PROXY=false',
    `SESSION_SECRET=${secret()}`,
    `FLAG_PEPPER=${secret()}`,
    'DATABASE_URL=file:./dev.db',
    'TIMER_MODE=event',
    'EVENT_DURATION_MINUTES=60',
    'EVENT_MODE=scheduled',
    `ADMIN_ALLOWED_IPS=${[...new Set(adminIps)].join(',')}`,
    `BACKUP_DIR=${backupDir}`,
    '',
  ];
  writeFileSync(envPath, lines.join('\n'));
  if (!isWin) execFileSync('chmod', ['600', envPath]);
  console.log(`\nWrote ${envPath}`);
  console.log(`  Players will open:  ${origin}`);
  console.log(`  Admin allowed from: ${[...new Set(adminIps)].join(', ')}${adminIp ? '' : '  (add your laptop with --admin-ip)'}`);

  console.log('\nApplying migrations...');
  run('npm', ['run', 'db:deploy', '-w', '@cydemic/api']);

  console.log('Seeding challenges (locked)...');
  // Seed with the production .env. EVENT_MODE=scheduled so nothing opens yet.
  run('npm', ['run', 'seed', '-w', '@cydemic/api', '--', '--update-event']);

  console.log('Rehashing flags with the production pepper...');
  run('npm', ['run', 'prod:rehash', '-w', '@cydemic/api']);

  console.log('\nNext steps:');
  console.log('  1. Create the organizer account:   npm run admin:create');
  console.log('  2. Open the Windows firewall:      scripts\\windows\\open-firewall.ps1 (admin PowerShell)');
  console.log('  3. Check everything:               npm run preflight');
  console.log('  4. Start the event:                start-event.cmd');
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : String(err));
  process.exit(1);
});
